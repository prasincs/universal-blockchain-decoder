fn generate_encoding_imports(encoding: &EncodingSpec) -> String {
    let mut imports = vec![];

    if let Some(ref var_enc) = encoding.var_encoding {
        match var_enc.as_str() {
            "varint" => imports.push("use decoder_encodings::varint::*;"),
            "rlp" => imports.push("use decoder_encodings::rlp::*;"),
            "compact-u16" => imports.push("use decoder_encodings::compact_u16::*;"),
            "uleb128" | "bcs" => imports.push("use decoder_encodings::bcs::*;"),
            _ => {}
        }
    }

    if !imports.is_empty() {
        format!("\n{}", imports.join("\n"))
    } else {
        String::new()
    }
}

