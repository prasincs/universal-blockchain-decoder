fn generate_hash_impl(encoding: &EncodingSpec) -> String {
    match encoding.hash.as_str() {
        "sha256" => r#"Sha256::digest(&self.raw_bytes).to_vec()"#.to_string(),
        "double-sha256" => r#"let hash1 = Sha256::digest(&self.raw_bytes);
        let hash2 = Sha256::digest(hash1);
        hash2.to_vec()"#
            .to_string(),
        "keccak256" => r#"Keccak256::digest(&self.raw_bytes).to_vec()"#.to_string(),
        _ => r#"unimplemented!("Hash algorithm not yet implemented")"#.to_string(),
    }
}

