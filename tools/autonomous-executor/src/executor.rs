    /// Execute a task
    pub async fn execute(&self, task: &Task, dry_run: bool) -> Result<String> {
        println!("\n{}", "=".repeat(80));
        println!("Executing Task: {}", task.title);
        println!("Phase: {}", task.phase);
        println!("Priority: {}", task.priority);
        println!("ROI Score: {:.2}", task.roi_score);
        println!(
            "Time Estimate: {}",
            task.time_estimate.as_ref().unwrap_or(&"N/A".to_string())
        );
        println!("{}", "=".repeat(80));
        println!();

        if dry_run {
            info!("[DRY RUN] Would execute task, but skipping...");
            return Ok("Dry run - no actual execution".to_string());
        }

        // Create branch name
        let timestamp = Utc::now().format("%Y%m%d-%H%M%S");
        let branch_name = format!("claude/automate-{}-{}", task.id, timestamp);

        // 1. Create and checkout branch
        info!("Creating branch: {}", branch_name);
        GitHelper::create_branch(&branch_name)?;

        // 2. Build prompt and invoke Claude Code
        let prompt = self.build_prompt(task);
        info!("Invoking Claude Code...");
        self.invoke_claude_code(&prompt).await?;

        // 3. Run quality checks
        info!("Running quality checks...");
        self.run_quality_checks()?;

        // 4. Run tests
        info!("Running tests...");
        self.run_tests()?;

        // 5. Commit changes
        let commit_msg = format!(
            "automate: {}\n\n{}\n\nGenerated by autonomous executor",
            task.title,
            &task.description[..task.description.len().min(200)]
        );
        info!("Committing changes...");
        GitHelper::add_all()?;
        GitHelper::commit(&commit_msg)?;

        // 6. Push branch
        info!("Pushing to remote...");
        GitHelper::push(&branch_name)?;

        Ok(format!(
            "Successfully completed task on branch {}",
            branch_name
        ))
    }

