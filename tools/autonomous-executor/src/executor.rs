        let anthropic_api_key = env::var("ANTHROPIC_API_KEY").ok();

        if anthropic_api_key.is_none() {
            warn!("ANTHROPIC_API_KEY not set - Claude Code invocation will be placeholder");
        }

        Ok(Self { anthropic_api_key })
